import { randomUUID } from 'crypto';
import path from 'path';
import {
  DEFAULT_DOCUMENTS_MAX_FILE_SIZE,
  DOCUMENT_MIME_TYPES,
  DocumentExtension,
} from './document.constants';

const MAX_ORIGINAL_NAME_LENGTH = 255;

/** Max upload size in bytes (DOCUMENTS_MAX_FILE_SIZE, default 20 MB). */
export function resolveDocumentsMaxFileSize(): number {
  const parsed = Number(process.env.DOCUMENTS_MAX_FILE_SIZE);
  return Number.isInteger(parsed) && parsed > 0
    ? parsed
    : DEFAULT_DOCUMENTS_MAX_FILE_SIZE;
}

/** Lower-cased extension if it is on the allowlist, otherwise null. */
export function getAllowedExtension(
  fileName: string,
): DocumentExtension | null {
  const extension = path.extname(fileName).slice(1).toLowerCase();
  return Object.prototype.hasOwnProperty.call(DOCUMENT_MIME_TYPES, extension)
    ? (extension as DocumentExtension)
    : null;
}

export function mimeTypeForExtension(extension: DocumentExtension): string {
  return DOCUMENT_MIME_TYPES[extension];
}

/** Random on-disk name; the user's file name is never used for storage. */
export function buildStorageKey(extension: DocumentExtension): string {
  return `${randomUUID()}.${extension}`;
}

/** Storage keys are generated by us; reject anything that could escape the dir. */
export function isSafeStorageKey(storageKey: string): boolean {
  return /^[a-f0-9-]{36}\.[a-z]{2,4}$/.test(storageKey);
}

function isControlChar(char: string): boolean {
  const code = char.charCodeAt(0);
  return code < 0x20 || code === 0x7f;
}

/**
 * Busboy decodes multipart file names as latin1; browsers send UTF-8 bytes.
 * Re-decode when the result is valid UTF-8, otherwise keep the original.
 */
export function decodeUploadedName(rawName: string): string {
  const isByteString = [...rawName].every((char) => char.charCodeAt(0) <= 0xff);
  const hasHighBytes = [...rawName].some((char) => char.charCodeAt(0) >= 0x80);
  if (!isByteString || !hasHighBytes) {
    return rawName;
  }
  const decoded = Buffer.from(rawName, 'latin1').toString('utf8');
  return decoded.includes('�') ? rawName : decoded;
}

/** Display name: no path parts, no control chars, bounded length. */
export function sanitizeOriginalName(rawName: string): string {
  const baseName = rawName.split(/[\\/]/).pop() ?? '';
  const cleaned = [...baseName]
    .map((char) => (isControlChar(char) ? '_' : char))
    .join('')
    .trim();
  const name = cleaned.length > 0 ? cleaned : 'document';
  if (name.length <= MAX_ORIGINAL_NAME_LENGTH) {
    return name;
  }
  const extension = path.extname(name).slice(0, 10);
  return name.slice(0, MAX_ORIGINAL_NAME_LENGTH - extension.length) + extension;
}

function encodeRfc5987(value: string): string {
  return encodeURIComponent(value).replace(
    /['()*]/g,
    (char) => `%${char.charCodeAt(0).toString(16).toUpperCase()}`,
  );
}

/** `attachment` with an ASCII fallback and an RFC 5987 UTF-8 filename*. */
export function buildContentDisposition(fileName: string): string {
  const safe = [...sanitizeOriginalName(fileName)]
    .map((char) => (char === '"' || char === '\\' ? '_' : char))
    .join('');
  const asciiFallback = [...safe]
    .map((char) => {
      const code = char.charCodeAt(0);
      return code >= 0x20 && code <= 0x7e ? char : '_';
    })
    .join('');
  return `attachment; filename="${asciiFallback}"; filename*=UTF-8''${encodeRfc5987(safe)}`;
}
